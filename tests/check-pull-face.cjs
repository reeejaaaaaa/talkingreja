const assert=require('node:assert/strict');
global.THREE=require('../vendor/three.min.js');
for(const file of ['model','deform','laugh-face','pull-face'])require('../'+file+'.js');
const m=MiniRheza.createCharacter(),soft=new SoftFaceDeformer(m.softMeshes,m.head),laugh=new FaceLaughAnimator(m),pull=new FacePullAnimator(m);
const neutral=m.softMeshes.map(mesh=>mesh.geometry.attributes.position.array.slice());
assert.equal(pull.targets.length,5);
pull.apply(1);
for(const {mesh,index} of pull.targets)assert.equal(mesh.morphTargetInfluences[index],1);
const lip=m.head.getObjectByName('Soft lower lip');
assert.equal(lip.geometry.morphAttributes.position.length,2,'Pull must preserve laugh morph');
laugh.apply(1,1);pull.apply(0);
assert(laugh.lips.every(mesh=>mesh.morphTargetInfluences[0]===1),'Laugh keeps control of its morph');
assert(pull.targets.every(({mesh,index})=>mesh.morphTargetInfluences[index]===0));
laugh.reset();pull.apply(1);
const anchor=new THREE.Vector3(.69,-.28,m.faceZ(.69,-.28));soft.begin('held',anchor,new THREE.Vector3(0,0,1),.53);soft.target('held',new THREE.Vector3(.8,.2,.1));for(let i=0;i<60;i++)soft.step(1/60);
assert(pull.targets.every(({mesh,index})=>mesh.morphTargetInfluences[index]===1),'Soft deformation must not reset held expression');
soft.reset();pull.reset();
m.softMeshes.forEach((mesh,i)=>assert.deepEqual(mesh.geometry.attributes.position.array,neutral[i]));
assert(pull.targets.every(({mesh,index})=>mesh.morphTargetInfluences[index]===0));
console.log('Pull expression passed: additive morphs, laugh priority, soft drag compatibility, exact neutral restoration.');
